def is_serious(text):
    """判断是否为应排除出搞笑内容/禁止配搞笑段子的严肃新闻"""
    if not text:
        return False
    text = str(text)
    for kw in SERIOUS_BLACKLIST:
        if kw in text:
            return True
    return False


def is_funny(text):
    """判断内容是否属于搞笑/幽默类"""
    if not text:
        return False
    text = str(text)
    return any(kw in text for kw in FUNNY_KEYWORDS)


def filter_funny(items):
    """
    从内容列表中筛出搞笑类条目，并排除严肃新闻。
    items: list of dict, 每个有 title
    返回搞笑条目列表
    """
    result = []
    for it in items:
        title = it.get("title") or it.get("topic") or ""
        if not title:
            continue
        if is_serious(title):
            continue
        if is_funny(title):
            result.append(it)
    return result


def exclude_serious(items):
    """排除严肃新闻条目（用于热点榜中剔除灾难/伤亡类，避免与笑话混排）"""
    result = []
    for it in items:
        title = it.get("title") or it.get("topic") or ""
        if is_serious(title):
            continue
        result.append(it)
    return result